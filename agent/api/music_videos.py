"""Music videos — put visuals under a finished song.

Three modes:
  VISUALIZER — cover image (or plain background) + waveform, done locally.
  FLOWKIT    — scenes generated by Flow Kit (:8100) from a lyric-aware plan,
               then concatenated and muxed with the song here.
  NATIVE     — Flow Music's own music-video feature, via the
               generate_music_video recipe.
"""
from pathlib import Path
from typing import Optional

import httpx
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

from agent import config
from agent.api.songs import queue
from agent.db import crud
from agent.services.flowmusic_api import music_video_credits
from agent.services.post_process import FFmpegError, concat, make_visualizer, mux, plan_scenes, probe_duration
from agent.utils.paths import videos_dir

router = APIRouter(prefix="/music-videos", tags=["music-videos"])


class MusicVideoIn(BaseModel):
    song_id: str
    mode: str = "FLOWKIT"
    orientation: str = "HORIZONTAL"
    clip_seconds: float = Field(config.DEFAULT_CLIP_SECONDS, ge=1, le=30)


class PlanPatch(BaseModel):
    plan: dict


class VisualizerIn(BaseModel):
    image_path: Optional[str] = None       # defaults to the song's cover art


class AttachIn(BaseModel):
    """Visuals to put under the song: one finished video, or clips in order."""
    video_path: Optional[str] = None
    clip_paths: list[str] = []
    fit: str = "loop"                       # loop | trim
    flowkit_video_id: Optional[str] = None


class NativeIn(BaseModel):
    prompt: str = ""                        # visual direction for Flow Music's video agent
    resolution: str = "720p"
    start_s: float = 0
    duration_s: Optional[float] = None      # default: whole song
    render_lyrics: bool = False
    take: Optional[int] = None              # which take (clip) to use; default the selected one
    confirm: bool = False                   # must be true: this spends credits
    conversation_id: Optional[str] = None   # Flow Music conversation holding the proposal
    recipe: Optional[str] = None            # a recorded recipe instead of the API


async def _mv_or_404(mid: str) -> dict:
    mv = await crud.get("music_video", mid)
    if not mv:
        raise HTTPException(404, "music video not found")
    return mv


async def _song_audio(song_id: str) -> tuple[dict, Path]:
    song = await crud.get("song", song_id)
    if not song:
        raise HTTPException(404, "song not found")
    if not song.get("audio_path") or not Path(song["audio_path"]).is_file():
        raise HTTPException(409, "song has no audio yet — generate or import it first")
    return song, Path(song["audio_path"])


@router.post("")
async def create_music_video(body: MusicVideoIn):
    if body.mode not in ("VISUALIZER", "FLOWKIT", "NATIVE"):
        raise HTTPException(400, "mode must be VISUALIZER, FLOWKIT or NATIVE")
    if body.orientation not in ("HORIZONTAL", "VERTICAL"):
        raise HTTPException(400, "orientation must be HORIZONTAL or VERTICAL")
    song, audio = await _song_audio(body.song_id)
    duration = song.get("audio_duration_s")
    if not duration:
        try:
            duration = await probe_duration(audio)
        except FFmpegError as e:
            raise HTTPException(500, str(e))
        await crud.update("song", song["id"], {"audio_duration_s": round(duration, 2)})
    plan = plan_scenes(duration, song.get("lyrics") or "", body.clip_seconds, bool(song.get("instrumental")))
    plan.update({"song_title": song["title"], "song_prompt": song.get("prompt"),
                 "orientation": body.orientation})
    return await crud.insert("music_video", {
        "project_id": song["project_id"], "song_id": song["id"], "mode": body.mode,
        "orientation": body.orientation, "plan": plan,
    })


@router.get("")
async def list_music_videos(project_id: Optional[str] = None, song_id: Optional[str] = None):
    return await crud.list_rows("music_video", {"project_id": project_id, "song_id": song_id})


@router.get("/{mid}")
async def get_music_video(mid: str):
    return await _mv_or_404(mid)


@router.put("/{mid}/plan")
async def put_plan(mid: str, body: PlanPatch):
    """Save the scene plan after prompts were written into each scene."""
    await _mv_or_404(mid)
    if not isinstance(body.plan.get("scenes"), list):
        raise HTTPException(400, "plan.scenes must be a list")
    return await crud.update("music_video", mid, {"plan": body.plan})


@router.delete("/{mid}")
async def delete_music_video(mid: str):
    if not await crud.delete("music_video", mid):
        raise HTTPException(404, "music video not found")
    return {"ok": True}


async def _output_path(mv: dict, suffix: str) -> Path:
    project = await crud.get("project", mv["project_id"])
    song = await crud.get("song", mv["song_id"])
    return videos_dir(project["slug"]) / f"{song['slug']}_{suffix}.mp4"


@router.post("/{mid}/visualizer")
async def render_visualizer(mid: str, body: VisualizerIn = VisualizerIn()):
    mv = await _mv_or_404(mid)
    song, audio = await _song_audio(mv["song_id"])
    image = body.image_path or song.get("cover_path")
    if image and not Path(image).expanduser().is_file():
        raise HTTPException(400, f"image not found: {image}")
    out = await _output_path(mv, "visualizer")
    await crud.update("music_video", mid, {"status": "PROCESSING", "error_message": None})
    try:
        await make_visualizer(audio, out, Path(image).expanduser() if image else None, mv["orientation"])
    except FFmpegError as e:
        await crud.update("music_video", mid, {"status": "FAILED", "error_message": str(e)})
        raise HTTPException(500, str(e))
    return await crud.update("music_video", mid, {"status": "COMPLETED", "output_path": str(out)})


@router.post("/{mid}/attach")
async def attach_visuals(mid: str, body: AttachIn):
    """Mux the song onto visuals made elsewhere (Flow Kit, stock, hand-edited)."""
    mv = await _mv_or_404(mid)
    _, audio = await _song_audio(mv["song_id"])
    if body.fit not in ("loop", "trim"):
        raise HTTPException(400, "fit must be loop or trim")
    clips = [Path(p).expanduser() for p in body.clip_paths]
    missing = [str(p) for p in clips if not p.is_file()]
    if body.video_path and not Path(body.video_path).expanduser().is_file():
        missing.append(body.video_path)
    if missing:
        raise HTTPException(400, f"files not found: {missing}")
    if not body.video_path and not clips:
        raise HTTPException(400, "give video_path or clip_paths")

    await crud.update("music_video", mid, {"status": "PROCESSING", "error_message": None,
                                           "flowkit_video_id": body.flowkit_video_id})
    try:
        if clips:
            source = await concat(clips, await _output_path(mv, "visuals"), mv["orientation"])
        else:
            source = Path(body.video_path).expanduser()
        out = await mux(source, audio, await _output_path(mv, "final"), body.fit, mv["orientation"])
    except FFmpegError as e:
        await crud.update("music_video", mid, {"status": "FAILED", "error_message": str(e)})
        raise HTTPException(500, str(e))
    return await crud.update("music_video", mid, {
        "status": "COMPLETED", "source_video_path": str(source), "output_path": str(out)})


@router.post("/{mid}/native")
async def native_music_video(mid: str, body: NativeIn = NativeIn()):
    mv = await _mv_or_404(mid)
    song = await crud.get("song", mv["song_id"])
    takes = song.get("takes") or []
    idx = body.take if body.take is not None else song.get("selected_take") or 0
    clip_id = (takes[idx].get("clip_id") if 0 <= idx < len(takes) else None) or song.get("remote_id")
    if not clip_id:
        raise HTTPException(409, "song has no Flow Music clip id — generate it through Flow Music first")
    song_len = (takes[idx].get("remote_duration_s") if 0 <= idx < len(takes) else None) \
        or song.get("audio_duration_s") or 0
    duration = body.duration_s or max(0.0, song_len - body.start_s)
    credits = music_video_credits(duration)
    if not body.confirm:
        raise HTTPException(402, {
            "message": "Flow Music music videos cost credits — resend with confirm=true",
            "estimated_credits": credits, "duration_s": round(duration, 1), "clip_id": clip_id,
        })
    aspect = "9:16" if mv["orientation"] == "VERTICAL" else "16:9"
    await crud.update("music_video", mid, {"status": "PROCESSING", "error_message": None})
    if body.recipe:
        return await queue("GENERATE_MUSIC_VIDEO", body.recipe, song, {
            "remote_id": clip_id, "prompt": body.prompt, "music_video_id": mid,
            "orientation": mv["orientation"]})
    return await queue("GENERATE_MUSIC_VIDEO", "native:video__create_music_video", song, {
        "clip_id": clip_id, "user_message": body.prompt, "aspect_ratio": aspect,
        "resolution": body.resolution, "start_s": body.start_s, "duration_s": round(duration, 2),
        "render_lyrics": body.render_lyrics, "music_video_id": mid, "estimated_credits": credits,
        "conversation_id": body.conversation_id,
        "flow_project_id": (await crud.get("project", mv["project_id"])).get("flow_music_project_id")
        or config.default_flow_project_id() or None,
    })


@router.get("/flowkit/health")
async def flowkit_health():
    try:
        async with httpx.AsyncClient(timeout=5) as client:
            r = await client.get(f"{config.FLOWKIT_URL}/health")
        return {"url": config.FLOWKIT_URL, "reachable": True, **r.json()}
    except (httpx.HTTPError, ValueError) as e:
        return {"url": config.FLOWKIT_URL, "reachable": False, "error": str(e)}
